"""Read-only search and reading of Hermes conversations in the Hermes chat database (state.db).

Searches the external-content FTS5 index messages_fts (rowid = messages.id) and reads messages with their tool
calls and tool results. Every connection is opened with mode=ro; nothing is ever written to the database. No numpy
or embedding imports: Hermes' own Python imports this module.
"""
from __future__ import annotations

import json
import math
import re
import sqlite3
import time
from datetime import datetime
from pathlib import Path
from typing import Any

from .store import FTS_TERM_CAP, SQLITE_BUSY_TIMEOUT_SECONDS

STATE_DB_NAME = "state.db"
FTS_TABLE = "messages_fts"
DEFAULT_SEARCH_RESULTS = 10
MAX_SEARCH_RESULTS = 50
EXCERPT_CHARS = 300
# The excerpt starts this many characters before the first match (a third of the window), so the match is visible.
EXCERPT_LEAD_CHARS = EXCERPT_CHARS // 3
NEIGHBOR_EXCERPT_CHARS = 200
READ_CONTENT_CHARS = 20_000
TOOL_RESULT_CHARS = 4_000
MAX_CONTEXT = 10
SESSION_SUFFIX_MIN_CHARS = 6
ROLES = ("user", "assistant", "tool", "system")
ORDER_RECENT, ORDER_RANK = "recent", "rank"
ORDERS = (ORDER_RECENT, ORDER_RANK)
# Period listings (no query): chat_period here and mem_period in mcp_server.
ORDER_NEWEST, ORDER_OLDEST = "newest", "oldest"
PERIOD_ORDERS = (ORDER_NEWEST, ORDER_OLDEST)
DEFAULT_PERIOD_RESULTS = 20
MAX_PERIOD_SESSIONS = 50
# A relative time "<N>h", "<N>d" or "<N>w": N (a positive integer) hours, days or weeks before now.
_RELATIVE_TIME = re.compile(r"([1-9][0-9]*)([hdw])", flags=re.IGNORECASE)
_RELATIVE_UNIT_SECONDS = {"h": 3_600.0, "d": 86_400.0, "w": 604_800.0}
# state_meta keys Hermes keeps while it rebuilds the FTS index (results may then be missing).
REBUILD_KEYS = ("fts_rebuild_high_water", "fts_rebuild_progress")
_LIKE_ESCAPE = "\\"
# FTS5 words of a query used to place the excerpt; operators are no search words.
_QUERY_WORD = re.compile(r"[\w-]{2,}", flags=re.UNICODE)
_FTS_OPERATORS = frozenset({"AND", "OR", "NOT", "NEAR"})
_FTS_COLUMNS = frozenset({"content", "tool_name", "tool_calls"})
# A rewrite token needs one word character; a token of punctuation only can match nothing.
_WORD_CHARACTER = re.compile(r"\w", flags=re.UNICODE)

# Hermes gateway notifications stored as role=user. Must equal INTERNAL_NOTIFICATION_FOOTER in
# hermes-agent/gateway/run_notifications.py (appended once, after trailing whitespace is removed).
NOTIFICATION_FOOTER = ("[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. "
                       "Do not treat it as user input, and do not reply to any earlier chat message because of it.]")
# Older notifications from before the footer existed start with one of these; so do the summaries Hermes writes
# when it compacts a conversation (the user's own words stay in the compacted original rows).
NOTIFICATION_PREFIXES = ("[IMPORTANT: Background process", "[ASYNC DELEGATION BATCH COMPLETE",
                         "[CONTEXT COMPACTION")
# Messages that start like this carry words a human wrote, so they are never notifications.
HUMAN_PREFIXES = ("[OUT-OF-BAND USER MESSAGE", "[Context from the interrupted assistant response]")
# Characters rtrim removes before the footer check (Python's str.rstrip ASCII whitespace).
_TRAILING_WHITESPACE = " \t\n\r\x0b\x0c"
DEFAULT_EXCLUDE_NOTIFICATIONS_SEARCH = False
DEFAULT_EXCLUDE_NOTIFICATIONS_PERIOD = True

_MESSAGE_COLUMNS = ("messages.id, messages.session_id, messages.role, messages.content, messages.tool_call_id, "
                    "messages.tool_calls, messages.tool_name, messages.timestamp, messages.active")


class ChatHistoryError(Exception):
    """A failure with a stable code (invalid, not_found, unavailable) and a message."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


# Actions the authorizer lets through; every other one (INSERT, UPDATE, DELETE, CREATE, DROP, ALTER, ATTACH,
# DETACH, ...) is denied. No immutable=1: Hermes may be writing the WAL, and an immutable reader would miss it.
_ALLOWED_ACTIONS = frozenset({sqlite3.SQLITE_READ, sqlite3.SQLITE_SELECT, sqlite3.SQLITE_FUNCTION,
                              sqlite3.SQLITE_TRANSACTION})
_QUERY_ONLY_PRAGMA = "query_only"
_QUERY_ONLY_ON_VALUES = frozenset({"on", "1", "true", "yes"})
# PRAGMAs allowed without a value (they only report); with a value only query_only = ON is allowed.
_READ_PRAGMAS = frozenset({_QUERY_ONLY_PRAGMA, "table_info", "table_xinfo", "table_list", "index_list", "index_info",
                           "index_xinfo", "foreign_key_list", "database_list", "data_version", "schema_version",
                           "user_version", "journal_mode", "page_size", "page_count", "encoding",
                           "compile_options", "function_list", "module_list", "pragma_list"})


def _readonly_authorizer(action: int, arg1: str | None, arg2: str | None, database: str | None,
                         source: str | None) -> int:
    """sqlite3 authorizer of state.db connections: reads, read-only PRAGMAs and transaction begin/end only."""
    if action in _ALLOWED_ACTIONS:
        return sqlite3.SQLITE_OK
    if action == sqlite3.SQLITE_PRAGMA:
        name = (arg1 or "").lower()
        if arg2 is None and name in _READ_PRAGMAS:
            return sqlite3.SQLITE_OK
        if name == _QUERY_ONLY_PRAGMA and arg2.strip().strip("'\"").lower() in _QUERY_ONLY_ON_VALUES:
            return sqlite3.SQLITE_OK
    return sqlite3.SQLITE_DENY


def open_readonly(path: Path) -> sqlite3.Connection:
    """The one way this module opens state.db. Three locks against writes: a mode=ro URI, PRAGMA query_only = ON
    and an authorizer that denies everything but reads."""
    path = Path(path)
    if not path.is_file():
        raise ChatHistoryError("not_found", "Hermes chat database does not exist")
    connection = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True, timeout=SQLITE_BUSY_TIMEOUT_SECONDS)
    try:
        connection.execute("PRAGMA query_only = ON")
        connection.set_authorizer(_readonly_authorizer)
    except BaseException:
        connection.close()
        raise
    connection.row_factory = sqlite3.Row
    return connection


class _ReadOnlyChatDatabase:
    """`with _ReadOnlyChatDatabase(path) as conn`: an open_readonly connection, closed on exit."""

    def __init__(self, path: Path) -> None:
        self.path = Path(path)
        self.connection: sqlite3.Connection | None = None

    def __enter__(self) -> sqlite3.Connection:
        self.connection = open_readonly(self.path)
        return self.connection

    def __exit__(self, *exc_info: Any) -> None:
        if self.connection is not None:
            self.connection.close()


def chat_database_path(home: Path) -> Path:
    return Path(home) / STATE_DB_NAME


# -- argument checks -----------------------------------------------------------------------------

def _search_limit(value: Any) -> int:
    if type(value) is not int or not 1 <= value <= MAX_SEARCH_RESULTS:
        raise ChatHistoryError("invalid", f"limit must be an integer from 1 to {MAX_SEARCH_RESULTS}")
    return value


def _context(value: Any) -> int:
    if type(value) is not int or not 0 <= value <= MAX_CONTEXT:
        raise ChatHistoryError("invalid", f"context must be an integer from 0 to {MAX_CONTEXT}")
    return value


def _message_id(value: Any) -> int:
    if type(value) is not int:
        raise ChatHistoryError("invalid", "message_id must be an integer")
    return value


def _optional_text(name: str, value: Any) -> str | None:
    if value is None:
        return None
    if not isinstance(value, str) or not value.strip():
        raise ChatHistoryError("invalid", f"{name} must be a non-empty string")
    return value.strip()


def _flag(name: str, value: Any) -> bool:
    if type(value) is not bool:
        raise ChatHistoryError("invalid", f"{name} must be true or false")
    return value


def _choice(name: str, value: Any, choices: tuple[str, ...]) -> str:
    if value not in choices:
        raise ChatHistoryError("invalid", f"{name} must be one of: {', '.join(choices)}")
    return value


def parse_time(name: str, value: Any, now: float | None = None) -> float | None:
    """Unix epoch seconds of a number, an ISO 8601 string (no time zone: local time) or a relative time
    "<N>h" / "<N>d" / "<N>w" (N >= 1 hours, days or weeks before *now*, default time.time())."""
    if value is None:
        return None
    if type(value) in (int, float):
        if not math.isfinite(value):
            raise ChatHistoryError("invalid", f"{name} must be a finite number")
        return float(value)
    if isinstance(value, str) and value.strip():
        relative = _RELATIVE_TIME.fullmatch(value.strip())
        if relative is not None:
            try:
                seconds = int(relative.group(1)) * _RELATIVE_UNIT_SECONDS[relative.group(2).lower()]
            except (OverflowError, ValueError):  # more digits than a float holds
                raise ChatHistoryError("invalid", f"{name} is too far in the past") from None
            return (time.time() if now is None else now) - seconds
        try:
            return datetime.fromisoformat(value.strip()).timestamp()
        except (ValueError, OverflowError, OSError):
            pass
    raise ChatHistoryError("invalid", f"{name} must be a Unix epoch number, an ISO 8601 date/time string or a "
                                      f"relative time such as 24h, 7d or 2w")


def parse_period(since: Any, until: Any) -> tuple[float, float]:
    """(since, until) epoch seconds of a period listing: since is required, until defaults to now, since < until."""
    if since is None:
        raise ChatHistoryError("invalid", "since is required")
    now = time.time()
    start = parse_time("since", since, now)
    end = now if until is None else parse_time("until", until, now)
    if not math.isfinite(start) or not math.isfinite(end):
        raise ChatHistoryError("invalid", "since and until must be finite times")
    if start >= end:
        raise ChatHistoryError("invalid", "since must be earlier than until")
    return start, end


def _like_escape(text: str) -> str:
    return text.replace(_LIKE_ESCAPE, _LIKE_ESCAPE * 2).replace("%", _LIKE_ESCAPE + "%").replace(
        "_", _LIKE_ESCAPE + "_")


# -- row shaping ---------------------------------------------------------------------------------

def _local_time(timestamp: Any) -> str | None:
    try:
        return datetime.fromtimestamp(float(timestamp)).isoformat(timespec="seconds")
    except (TypeError, ValueError, OverflowError, OSError):
        return None


def _tool_call_list(tool_calls_json: Any) -> list[dict]:
    """The tool calls of an assistant row as dicts; malformed JSON or entries are skipped."""
    if not isinstance(tool_calls_json, str) or not tool_calls_json.strip():
        return []
    try:
        calls = json.loads(tool_calls_json)
    except ValueError:
        return []
    return [call for call in calls if isinstance(call, dict)] if isinstance(calls, list) else []


def _call_name(call: dict) -> str | None:
    function = call.get("function")
    name = function.get("name") if isinstance(function, dict) else None
    return name if isinstance(name, str) else None


class _Unparsed(str):
    """An arguments string that is no JSON, kept as it is."""


def _call_arguments(call: dict) -> Any:
    """arguments as a JSON value when the string parses, else the string itself (None when there are none)."""
    function = call.get("function")
    arguments = function.get("arguments") if isinstance(function, dict) else None
    if not isinstance(arguments, str):
        return arguments
    try:
        return json.loads(arguments)
    except ValueError:
        return _Unparsed(arguments)


def _call_arguments_text(call: dict) -> str:
    """Readable arguments text: parsed JSON written again without \\uXXXX escapes, else the original string."""
    arguments = _call_arguments(call)
    if arguments is None:
        return ""
    if isinstance(arguments, _Unparsed):
        return str(arguments)
    return json.dumps(arguments, ensure_ascii=False)


def _call_ids(calls: list[dict]) -> list[str]:
    return [call["id"] for call in calls if isinstance(call.get("id"), str)]


def _query_words(query: str) -> list[str]:
    """Lower-case search words of an FTS5 expression (operators and column names left out)."""
    words = []
    for match in _QUERY_WORD.finditer(query):
        word = match.group(0)
        if word in _FTS_OPERATORS:
            continue
        if word in _FTS_COLUMNS and query[match.end():].lstrip().startswith(":"):
            continue
        words.append(word.lower())
    return words


def _first_match(text: str, words: list[str]) -> int:
    """Index of the earliest occurrence of any word in text (case-insensitive), -1 when none."""
    lowered = text.lower()
    positions = [position for position in (lowered.find(word) for word in words) if position >= 0]
    return min(positions) if positions else -1


def _window(text: str, position: int, size: int) -> str:
    start = max(0, position - EXCERPT_LEAD_CHARS) if position >= 0 else 0
    return text[start:start + size]


def search_excerpt(content: Any, calls: list[dict], words: list[str]) -> str:
    """Up to EXCERPT_CHARS around the first matching word: content first, else the tool call arguments, else the
    start of the content."""
    content_text = content if isinstance(content, str) else ""
    position = _first_match(content_text, words)
    if position >= 0:
        return _window(content_text, position, EXCERPT_CHARS)
    arguments_text = "\n".join(filter(None, (_call_arguments_text(call) for call in calls)))
    position = _first_match(arguments_text, words)
    if position >= 0:
        return _window(arguments_text, position, EXCERPT_CHARS)
    return (content_text or arguments_text)[:EXCERPT_CHARS]


def _base_fields(row: sqlite3.Row) -> dict:
    return {"message_id": row["id"], "session_id": row["session_id"], "time": _local_time(row["timestamp"]),
            "timestamp": row["timestamp"], "role": row["role"], "tool_name": row["tool_name"],
            "tool_call_id": row["tool_call_id"], "active": row["active"]}


def _clip(text: Any, size: int) -> tuple[str, bool]:
    content = text if isinstance(text, str) else ("" if text is None else str(text))
    return (content[:size], True) if len(content) > size else (content, False)


# -- database checks -----------------------------------------------------------------------------

def _has_table(connection: sqlite3.Connection, name: str) -> bool:
    row = connection.execute("SELECT 1 FROM sqlite_master WHERE name = ? AND type IN ('table', 'view')",
                             (name,)).fetchone()
    return row is not None


def index_rebuilding(connection: sqlite3.Connection) -> bool:
    """True while state_meta holds an FTS rebuild key (search results may be missing)."""
    if not _has_table(connection, "state_meta"):
        return False
    placeholders = ", ".join("?" for _ in REBUILD_KEYS)
    row = connection.execute(f"SELECT 1 FROM state_meta WHERE key IN ({placeholders}) LIMIT 1",
                             REBUILD_KEYS).fetchone()
    return row is not None


# -- search --------------------------------------------------------------------------------------

class _SearchFilter:
    """WHERE clauses and parameters of one search; values only ever travel as SQL parameters."""

    def __init__(self) -> None:
        self.clauses: list[str] = []
        self.parameters: list[Any] = []

    def add(self, clause: str, *parameters: Any) -> None:
        self.clauses.append(clause)
        self.parameters.extend(parameters)


def _starts_with_any(column: str, prefixes: tuple[str, ...]) -> tuple[str, list[str]]:
    """SQL OR of exact (case-sensitive) prefix tests of column, and its parameters."""
    clause = " OR ".join(f"substr({column}, 1, {len(prefix)}) = ?" for prefix in prefixes)
    return clause, list(prefixes)


def _add_notification_exclusion(search_filter: _SearchFilter) -> None:
    """Drop role=user rows whose text ends with NOTIFICATION_FOOTER (trailing whitespace removed) or starts with a
    NOTIFICATION_PREFIXES entry, unless it starts with a HUMAN_PREFIXES entry. Done in SQL so LIMIT counts the rows
    that are left."""
    content = "coalesce(messages.content, '')"
    trimmed = f"rtrim({content}, ?)"
    old_clause, old_parameters = _starts_with_any(content, NOTIFICATION_PREFIXES)
    human_clause, human_parameters = _starts_with_any(content, HUMAN_PREFIXES)
    search_filter.add(
        f"NOT (messages.role = 'user' AND (substr({trimmed}, -{len(NOTIFICATION_FOOTER)}) = ? OR {old_clause}) "
        f"AND NOT ({human_clause}))",
        _TRAILING_WHITESPACE, NOTIFICATION_FOOTER, *old_parameters, *human_parameters)


def _build_filter(session: str | None, role: str | None, tool_name: str | None, since: float | None,
                  until: float | None, exclude_notifications: bool = False) -> _SearchFilter:
    search_filter = _SearchFilter()
    if exclude_notifications:
        _add_notification_exclusion(search_filter)
    if session is not None:
        if len(session) < SESSION_SUFFIX_MIN_CHARS:
            raise ChatHistoryError("invalid", f"session must be a full session id or its last "
                                              f"{SESSION_SUFFIX_MIN_CHARS} or more characters")
        search_filter.add(f"(messages.session_id = ? OR messages.session_id LIKE '%' || ? ESCAPE '{_LIKE_ESCAPE}')",
                          session, _like_escape(session))
    if role is not None:
        search_filter.add("messages.role = ?", role)
    if tool_name is not None:
        search_filter.add(f"(messages.tool_name = ? OR (messages.role = 'assistant' AND messages.tool_calls LIKE ? "
                          f"ESCAPE '{_LIKE_ESCAPE}'))", tool_name, f'%"{_like_escape(tool_name)}"%')
    if since is not None:
        search_filter.add("messages.timestamp >= ?", since)
    if until is not None:
        search_filter.add("messages.timestamp < ?", until)
    return search_filter


def _calls_tool(row: sqlite3.Row, tool_name: str) -> bool:
    """The SQL LIKE prefilter checked again on the parsed tool calls."""
    if row["tool_name"] == tool_name:
        return True
    return any(_call_name(call) == tool_name for call in _tool_call_list(row["tool_calls"]))


def rewrite_fts_query(query: str) -> str:
    """OR of the whitespace-separated tokens, each quoted as an FTS5 string ('"' doubled), at most FTS_TERM_CAP;
    "0.61" stays whole (FTS5 reads it as the phrase 0 61). Empty when no token has a word character."""
    tokens = [token for token in query.split() if _WORD_CHARACTER.search(token)]
    return " OR ".join('"' + token.replace('"', '""') + '"' for token in tokens[:FTS_TERM_CAP])


def _search_rows(connection: sqlite3.Connection, match: str, search_filter: _SearchFilter, order: str,
                 tool_name: str | None, limit: int) -> list[sqlite3.Row]:
    where = " AND ".join([f"{FTS_TABLE} MATCH ?", *search_filter.clauses])
    order_by = (f"bm25({FTS_TABLE}), messages.id DESC" if order == ORDER_RANK
                else "messages.timestamp DESC, messages.id DESC")
    sql = (f"SELECT {_MESSAGE_COLUMNS} FROM {FTS_TABLE} JOIN messages ON messages.id = {FTS_TABLE}.rowid "
           f"WHERE {where} ORDER BY {order_by}")
    parameters: list[Any] = [match, *search_filter.parameters]
    if tool_name is None:  # no Python recheck: SQL can cut the rows
        sql += " LIMIT ?"
        parameters.append(limit)
    rows: list[sqlite3.Row] = []
    for row in connection.execute(sql, parameters):
        if tool_name is None or _calls_tool(row, tool_name):
            rows.append(row)
            if len(rows) >= limit:
                break
    return rows


def _search_item(row: sqlite3.Row, words: list[str]) -> dict:
    calls = _tool_call_list(row["tool_calls"])
    item = _base_fields(row)
    item["tool_calls"] = ([{"id": call.get("id"), "name": _call_name(call)} for call in calls]
                          if row["role"] == "assistant" else [])
    item["excerpt"] = search_excerpt(row["content"], calls, words)
    return item


def search(database: Path, query: Any, session: Any = None, role: Any = None, tool_name: Any = None,
           since: Any = None, until: Any = None, order: Any = ORDER_RECENT,
           limit: Any = DEFAULT_SEARCH_RESULTS,
           exclude_notifications: Any = DEFAULT_EXCLUDE_NOTIFICATIONS_SEARCH) -> dict:
    """FTS5 search of Hermes messages; a query FTS5 rejects is retried once as an OR of its quoted words."""
    if not isinstance(query, str) or not query.strip():
        raise ChatHistoryError("invalid", "query must be a non-empty string")
    limit = _search_limit(limit)
    order = _choice("order", order, ORDERS)
    role = _optional_text("role", role)
    if role is not None:
        _choice("role", role, ROLES)
    tool_name = _optional_text("tool_name", tool_name)
    search_filter = _build_filter(_optional_text("session", session), role, tool_name,
                                  parse_time("since", since), parse_time("until", until),
                                  _flag("exclude_notifications", exclude_notifications))
    query = query.strip()
    try:
        with _ReadOnlyChatDatabase(database) as connection:
            if not _has_table(connection, FTS_TABLE):
                raise ChatHistoryError("unavailable", "Hermes chat search index is missing")
            rewritten = None
            try:
                rows = _search_rows(connection, query, search_filter, order, tool_name, limit)
            except sqlite3.OperationalError:
                rewritten = rewrite_fts_query(query)
                if not rewritten:
                    raise ChatHistoryError("invalid", "query is no valid FTS5 expression and has no search words")
                rows = _search_rows(connection, rewritten, search_filter, order, tool_name, limit)
            words = _query_words(query)
            payload: dict[str, Any] = {"results": [_search_item(row, words) for row in rows], "count": len(rows),
                                       "index_rebuilding": index_rebuilding(connection)}
            if rewritten is not None:
                payload["query_rewritten"] = rewritten
            return payload
    except sqlite3.DatabaseError as exc:
        raise ChatHistoryError("unavailable", f"Hermes chat database read failed: {exc}") from None


# -- period --------------------------------------------------------------------------------------

def _period_rows(connection: sqlite3.Connection, search_filter: _SearchFilter, order: str, tool_name: str | None,
                 limit: int) -> list[sqlite3.Row]:
    """Up to limit + 1 messages of the filter in time order (the extra row tells the list was cut)."""
    direction = "ASC" if order == ORDER_OLDEST else "DESC"
    sql = (f"SELECT {_MESSAGE_COLUMNS} FROM messages WHERE {' AND '.join(search_filter.clauses)} "
           f"ORDER BY messages.timestamp {direction}, messages.id {direction}")
    parameters: list[Any] = list(search_filter.parameters)
    wanted = limit + 1
    if tool_name is None:  # no Python recheck: SQL can cut the rows
        sql += " LIMIT ?"
        parameters.append(wanted)
    rows: list[sqlite3.Row] = []
    for row in connection.execute(sql, parameters):
        if tool_name is None or _calls_tool(row, tool_name):
            rows.append(row)
            if len(rows) >= wanted:
                break
    return rows


class _SessionSpan:
    """First and last message time and message count of one conversation within a period."""

    __slots__ = ("session_id", "first", "last", "count")

    def __init__(self, session_id: Any, first: float, last: float, count: int) -> None:
        self.session_id = session_id
        self.first = first
        self.last = last
        self.count = count

    def add(self, timestamp: float) -> None:
        self.first = min(self.first, timestamp)
        self.last = max(self.last, timestamp)
        self.count += 1

    @staticmethod
    def last_of(span: "_SessionSpan") -> float:
        return span.last


def _session_spans(connection: sqlite3.Connection, search_filter: _SearchFilter,
                   tool_name: str | None) -> list[_SessionSpan]:
    """Every conversation with a message of the filter; with tool_name the SQL prefilter is checked again per row."""
    where = " AND ".join(search_filter.clauses)
    if tool_name is None:
        rows = connection.execute(
            f"SELECT messages.session_id, MIN(messages.timestamp), MAX(messages.timestamp), COUNT(*) FROM messages "
            f"WHERE {where} GROUP BY messages.session_id", search_filter.parameters)
        return [_SessionSpan(row[0], float(row[1]), float(row[2]), int(row[3])) for row in rows]
    spans: dict[Any, _SessionSpan] = {}
    for row in connection.execute(f"SELECT messages.session_id, messages.timestamp, messages.tool_name, "
                                  f"messages.tool_calls FROM messages WHERE {where}", search_filter.parameters):
        if not _calls_tool(row, tool_name):
            continue
        timestamp = float(row["timestamp"])
        span = spans.get(row["session_id"])
        if span is None:
            spans[row["session_id"]] = _SessionSpan(row["session_id"], timestamp, timestamp, 1)
        else:
            span.add(timestamp)
    return list(spans.values())


def _session_titles(connection: sqlite3.Connection, session_ids: list[Any]) -> dict[Any, Any]:
    """sessions.title of each id; {} when state.db has no sessions table or no title column."""
    if not session_ids or not _has_table(connection, "sessions"):
        return {}
    columns = {column[0] for column in connection.execute("SELECT * FROM sessions LIMIT 0").description}
    if "title" not in columns:
        return {}
    placeholders = ", ".join("?" for _ in session_ids)
    return {row[0]: row[1] for row in connection.execute(
        f"SELECT id, title FROM sessions WHERE id IN ({placeholders})", session_ids)}


def _session_summaries(connection: sqlite3.Connection, search_filter: _SearchFilter,
                       tool_name: str | None) -> tuple[list[dict], bool]:
    """The MAX_PERIOD_SESSIONS most recently active conversations of the period, and whether there were more."""
    spans = _session_spans(connection, search_filter, tool_name)
    spans.sort(key=_SessionSpan.last_of, reverse=True)
    kept = spans[:MAX_PERIOD_SESSIONS]
    titles = _session_titles(connection, [span.session_id for span in kept])
    summaries = [{"session_id": span.session_id, "title": titles.get(span.session_id),
                  "first_time": _local_time(span.first), "first_timestamp": span.first,
                  "last_time": _local_time(span.last), "last_timestamp": span.last,
                  "message_count": span.count} for span in kept]
    return summaries, len(spans) > len(kept)


def period(database: Path, since: Any, until: Any = None, session: Any = None, role: Any = None,
           tool_name: Any = None, order: Any = ORDER_NEWEST, limit: Any = DEFAULT_PERIOD_RESULTS,
           exclude_notifications: Any = DEFAULT_EXCLUDE_NOTIFICATIONS_PERIOD) -> dict:
    """Hermes messages with since <= timestamp < until, no FTS: a per-conversation summary of the whole period
    (sessions) and up to limit messages shaped like search results (excerpt = start of the text)."""
    limit = _search_limit(limit)
    order = _choice("order", order, PERIOD_ORDERS)
    role = _optional_text("role", role)
    if role is not None:
        _choice("role", role, ROLES)
    tool_name = _optional_text("tool_name", tool_name)
    start, end = parse_period(since, until)
    search_filter = _build_filter(_optional_text("session", session), role, tool_name, start, end,
                                  _flag("exclude_notifications", exclude_notifications))
    try:
        with _ReadOnlyChatDatabase(database) as connection:
            sessions, sessions_truncated = _session_summaries(connection, search_filter, tool_name)
            rows = _period_rows(connection, search_filter, order, tool_name, limit)
            results = [_search_item(row, []) for row in rows[:limit]]
            return {"since": _local_time(start), "until": _local_time(end), "sessions": sessions,
                    "sessions_truncated": sessions_truncated, "results": results, "count": len(results),
                    "truncated": len(rows) > limit}
    except sqlite3.DatabaseError as exc:
        raise ChatHistoryError("unavailable", f"Hermes chat database read failed: {exc}") from None


# -- read ----------------------------------------------------------------------------------------

def _message_row(connection: sqlite3.Connection, message_id: int) -> sqlite3.Row | None:
    return connection.execute(f"SELECT {_MESSAGE_COLUMNS} FROM messages WHERE messages.id = ?",
                              (message_id,)).fetchone()


def _tool_results(connection: sqlite3.Connection, session_id: Any, call_ids: list[str]) -> list[dict]:
    if not call_ids:
        return []
    placeholders = ", ".join("?" for _ in call_ids)
    rows = connection.execute(
        f"SELECT {_MESSAGE_COLUMNS} FROM messages WHERE messages.session_id = ? AND messages.role = 'tool' "
        f"AND messages.tool_call_id IN ({placeholders}) ORDER BY messages.id", (session_id, *call_ids)).fetchall()
    results = []
    for row in rows:
        content, truncated = _clip(row["content"], TOOL_RESULT_CHARS)
        results.append({"message_id": row["id"], "tool_call_id": row["tool_call_id"], "tool_name": row["tool_name"],
                        "time": _local_time(row["timestamp"]), "content": content, "truncated": truncated})
    return results


def _called_by(connection: sqlite3.Connection, row: sqlite3.Row) -> int | None:
    """message_id of the assistant row whose tool_calls hold this tool row's tool_call_id."""
    call_id = row["tool_call_id"]
    if not isinstance(call_id, str) or not call_id:
        return None
    candidates = connection.execute(
        f"SELECT messages.id, messages.tool_calls FROM messages WHERE messages.session_id = ? "
        f"AND messages.role = 'assistant' AND messages.tool_calls LIKE ? ESCAPE '{_LIKE_ESCAPE}' "
        f"ORDER BY messages.id DESC", (row["session_id"], f"%{_like_escape(call_id)}%"))
    for candidate in candidates:
        if call_id in _call_ids(_tool_call_list(candidate["tool_calls"])):
            return candidate["id"]
    return None


def _neighbor(row: sqlite3.Row) -> dict:
    content = row["content"] if isinstance(row["content"], str) else ""
    if not content:
        names = filter(None, (_call_name(call) for call in _tool_call_list(row["tool_calls"])))
        content = ", ".join(names)
    return {"message_id": row["id"], "role": row["role"], "time": _local_time(row["timestamp"]),
            "tool_name": row["tool_name"], "excerpt": content[:NEIGHBOR_EXCERPT_CHARS]}


def _neighbors(connection: sqlite3.Connection, row: sqlite3.Row, context: int) -> list[dict]:
    if context == 0:
        return []
    before = connection.execute(
        f"SELECT {_MESSAGE_COLUMNS} FROM messages WHERE messages.session_id = ? AND messages.id < ? "
        f"ORDER BY messages.id DESC LIMIT ?", (row["session_id"], row["id"], context)).fetchall()
    after = connection.execute(
        f"SELECT {_MESSAGE_COLUMNS} FROM messages WHERE messages.session_id = ? AND messages.id > ? "
        f"ORDER BY messages.id LIMIT ?", (row["session_id"], row["id"], context)).fetchall()
    return [_neighbor(neighbor) for neighbor in [*reversed(before), *after]]


def read(database: Path, message_id: Any, context: Any = 0) -> dict:
    """One message in full with its tool calls, their results (assistant), its caller (tool) and neighbours."""
    message_id = _message_id(message_id)
    context = _context(context)
    try:
        with _ReadOnlyChatDatabase(database) as connection:
            row = _message_row(connection, message_id)
            if row is None:
                raise ChatHistoryError("not_found", f"Hermes chat message {message_id} does not exist")
            calls = _tool_call_list(row["tool_calls"])
            content, truncated = _clip(row["content"], READ_CONTENT_CHARS)
            message = _base_fields(row)
            message.update({"content": content, "truncated": truncated,
                            "tool_calls": [{"id": call.get("id"), "name": _call_name(call),
                                            "arguments": _call_arguments(call)} for call in calls]})
            payload: dict[str, Any] = {"message": message}
            if row["role"] == "assistant":
                payload["tool_results"] = _tool_results(connection, row["session_id"], _call_ids(calls))
            if row["role"] == "tool":
                payload["called_by"] = _called_by(connection, row)
            payload["neighbors"] = _neighbors(connection, row, context)
            return payload
    except sqlite3.DatabaseError as exc:
        raise ChatHistoryError("unavailable", f"Hermes chat database read failed: {exc}") from None
